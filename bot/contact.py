u"""Как показать человека команде: имя ссылкой на профиль, ник и id.

AleX 13.09.2026: «у части людей в отчёте нет ни ника, ни телефона, только
ID — как с ними связаться?». Ник в Telegram необязателен, многие его не
заводят, а телефон бот не получает вовсе: Telegram отдаёт его ботам только
если человек сам нажмёт «поделиться контактом». Зато по id бот может дать
ссылку на профиль: нажал на имя — открылся человек, оттуда пишешь.
Проверено 14.09.2026 на человеке без ника: Telegram распознал ссылку
(сущность text_mention). Откроется ли профиль у менеджера, решают
настройки приватности самого человека — у большинства открывается.

Раньше эта строка была написана трижды — в старте, в заботе и в покупке —
и три копии расходились. Теперь одна.
"""
import html


def link(user_id: int, name: str | None) -> str:
    u"""Имя ссылкой на профиль Telegram — работает и у людей без ника."""
    return u'<a href="tg://user?id=%d">%s</a>' % (int(user_id), html.escape(name or u'без имени'))


def line(user_id: int, name: str | None, username: str | None, bold: bool = False) -> str:
    u"""«Имя · @ник · <id>» для сообщений команде; без ника — «без ника»."""
    who = link(user_id, name)
    if bold:
        who = u'<b>%s</b>' % who
    handle = u'@%s' % html.escape(username) if username else u'без ника'
    return u'%s · %s · <code>%s</code>' % (who, handle, int(user_id))
